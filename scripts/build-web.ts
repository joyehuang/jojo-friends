/**
 * Builds the private `@joyehuang/jojo-web` package (Jojo-only web runtime +
 * build-time static renderer) into dist-web/, checks it, and packs a tarball
 * into out-web/. Nothing here is published: the package is `private: true`,
 * `UNLICENSED`, and `npm publish` refuses private packages.
 *
 *   pnpm build:web
 */
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { build, minify, type Plugin } from 'vite'
import { getCharacter, resolveConfig, staticFrame } from '../src/library'
import { JOJO } from '../src/library/characters/jojo'
import { JojoSvg, makeIds } from '../src/library/JojoSvg'
import { checkWebDist } from './check-web-dist'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = resolve(ROOT, 'dist-web')
const PACK = resolve(ROOT, 'out-web')
const pkg = JSON.parse(readFileSync(resolve(ROOT, 'package.json'), 'utf8'))

/** Family members a site may show as static art (About page). Keep this short. */
export const WEB_FRIENDS = ['h02', 'o02', 'h06'] as const
const FRIEND_SIZE = 56
const PLACEHOLDER = 'JIDPX'
const VERSION = '0.1.0'

function generateFriends() {
  const entries = WEB_FRIENDS.map((id) => {
    const ch = getCharacter(id)
    if (!ch) throw new Error(`unknown friend ${id}`)
    const cfg = resolveConfig({ character: ch, emotion: 'calm', size: FRIEND_SIZE, motion: 'static' }, true)
    const svg = renderToStaticMarkup(
      createElement(JojoSvg, { frame: staticFrame(cfg), cfg, ids: makeIds(PLACEHOLDER), decorative: true }),
    )
    if (svg.split(PLACEHOLDER).length < 3) throw new Error('placeholder ids missing')
    return [id, { id, name: ch.name, persona: ch.persona, svg }] as const
  })
  const body =
    '// generated by scripts/build-web.ts — do not edit\n' +
    `export const FRIEND_PLACEHOLDER = ${JSON.stringify(PLACEHOLDER)}\n` +
    `export const FRIEND_SIZE = ${FRIEND_SIZE}\n` +
    `export const FRIEND_SVGS = ${JSON.stringify(Object.fromEntries(entries), null, 1)} as const\n`
  writeFileSync(resolve(ROOT, 'src/web/friends.generated.ts'), body)
}

/**
 * Jojo's character object, serialised. The approved Jojo is frozen constants
 * run through the shape builder once at import; the web runtime only reads the
 * finished outlines, rig and palette, so it gets them as a literal and the
 * shape solver (and the authoring metadata) stay out of the browser. The parity
 * test renders every emotion x status through both and compares bytes.
 */
function generateJojo() {
  const { spec: _spec, source: _source, form: _form, persona: _persona, cleanup: _cleanup, fit: _fit, ...rest } = JOJO
  const slim = {
    ...rest,
    shell: { d: JOJO.shell.d, box: JOJO.shell.box },
    face: { d: JOJO.face.d, box: JOJO.face.box },
  }
  const body =
    '// generated by scripts/build-web.ts from src/library/characters/jojo.ts — do not edit\n' +
    "import type { Character } from '../library/character'\n" +
    `export const JOJO = ${JSON.stringify(slim)} as unknown as Character\n`
  writeFileSync(resolve(ROOT, 'src/web/jojo.generated.ts'), body)
}

/** Swap the 26-character registry for the Jojo-only one, and prove it held. */
function jojoOnly(): Plugin {
  const registry = resolve(ROOT, 'src/web/registry.ts')
  const jojoLiteral = resolve(ROOT, 'src/web/jojo.generated.ts')
  const jojoSource = resolve(ROOT, 'src/library/characters/jojo.ts')
  return {
    name: 'jojo-only-registry',
    enforce: 'pre',
    async resolveId(source, importer) {
      if (source === './characters' && importer?.replace(/\\/g, '/').endsWith('/src/library/config.ts')) return registry
      if (importer && /characters\/jojo$/.test(source)) {
        const r = await this.resolve(source, importer, { skipSelf: true })
        if (r?.id === jojoSource) return jojoLiteral
      }
      return null
    },
    generateBundle(_, bundle) {
      for (const chunk of Object.values(bundle)) {
        if (chunk.type !== 'chunk') continue
        for (const [id, m] of Object.entries(chunk.modules)) {
          const rel = id.replace(/\\/g, '/')
          if (/\/src\/library\/characters\/(?!jojo\.ts$)/.test(rel) && m.renderedLength > 0) {
            this.error(`family data leaked into ${chunk.fileName}: ${rel} (${m.renderedLength} B)`)
          }
          if (/\/src\/library\/(render\.ts|index\.ts|character\.ts)$/.test(rel) && m.renderedLength > 2000) {
            this.warn(`${rel} contributes ${m.renderedLength} B to ${chunk.fileName}`)
          }
        }
      }
    },
  }
}

async function buildEntry(entry: string, fileName: string, ssr: boolean) {
  await build({
    root: ROOT,
    configFile: false,
    logLevel: 'warn',
    publicDir: false,
    plugins: [jojoOnly()],
    esbuild: { jsx: 'automatic' },
    define: { 'process.env.NODE_ENV': '"production"' },
    build: {
      outDir: OUT,
      emptyOutDir: false,
      sourcemap: false,
      minify: 'esbuild',
      ssr: ssr ? resolve(ROOT, entry) : undefined,
      target: ssr ? 'node20' : 'es2022',
      lib: ssr ? undefined : { entry: resolve(ROOT, entry), formats: ['es'], fileName: () => fileName },
      rollupOptions: {
        external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/server'],
        output: ssr ? { entryFileNames: fileName, format: 'es' } : undefined,
      },
    },
  })
}

