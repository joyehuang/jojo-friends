async function main() {
  rmSync(OUT, { recursive: true, force: true })
  mkdirSync(OUT, { recursive: true })
  generateFriends()
  generateJojo()
  await buildEntry('src/web/runtime.ts', 'runtime.js', false)
  await buildEntry('src/web/static.tsx', 'static.js', true)
  // Vite keeps whitespace in ES library output; minify for real so the
  // package's size reflects what a consumer ships (the consumer re-minifies).
  for (const f of ['runtime.js', 'static.js']) {
    const file = resolve(OUT, f)
    const out = await minify(f, readFileSync(file, 'utf8'), { module: true, compress: true, mangle: true })
    writeFileSync(file, out.code)
  }
  writeFileSync(resolve(OUT, 'runtime.d.ts'), RUNTIME_DTS)
  writeFileSync(resolve(OUT, 'static.d.ts'), STATIC_DTS)
  writeFileSync(resolve(OUT, 'NOTICE'), NOTICE)
  const sourceCommit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: ROOT }).toString().trim()
  writeFileSync(
    resolve(OUT, 'package.json'),
    JSON.stringify(
      {
        name: '@joyehuang/jojo-web',
        version: VERSION,
        private: true,
        license: 'UNLICENSED',
        description: 'Jojo-only web runtime and build-time static renderer (private).',
        type: 'module',
        sideEffects: false,
        exports: {
          './runtime': { types: './runtime.d.ts', default: './runtime.js' },
          './static': { types: './static.d.ts', default: './static.js' },
          './package.json': './package.json',
        },
        files: ['runtime.js', 'runtime.d.ts', 'static.js', 'static.d.ts', 'NOTICE'],
        peerDependencies: { react: pkg.dependencies.react, 'react-dom': pkg.dependencies['react-dom'] },
        jojoWeb: { sourceCommit, friends: WEB_FRIENDS },
      },
      null,
      2,
    ) + '\n',
  )
  const report = checkWebDist(OUT, [...WEB_FRIENDS])
  mkdirSync(PACK, { recursive: true })
  const packed = execFileSync('npm', ['pack', '--pack-destination', PACK, '--json'], { cwd: OUT }).toString()
  const file = resolve(PACK, JSON.parse(packed)[0].filename)
  const sha256 = createHash('sha256').update(readFileSync(file)).digest('hex')
  const summary = { version: VERSION, sourceCommit, tarball: file, sha256, ...report }
  writeFileSync(resolve(PACK, `jojo-web-${VERSION}.report.json`), JSON.stringify(summary, null, 2) + '\n')
  console.log(JSON.stringify(summary, null, 2))
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
