// Solves every companion's placements (brows, cheeks, status shapes) from
// scratch and writes src/library/characters/solved.generated.ts, so the
// library doesn't run the solvers at load time.
//   pnpm exec tsx scripts/gen-solved.ts            (write)
//   pnpm exec tsx scripts/gen-solved.ts --check    (exit 1 if stale)
import { readFileSync, writeFileSync } from 'node:fs'
import { buildCharacter, type Solved } from '../src/library/character'
import { CHARACTER_LIST } from '../src/library/characters'

const OUT = 'src/library/characters/solved.generated.ts'

export function solveAll(): Record<string, Solved> {
  const out: Record<string, Solved> = {}
  for (const c of CHARACTER_LIST) {
    if (!c.rig) continue // Jojo is hand-frozen
    out[c.id] = buildCharacter(c.spec, { solve: true }).solved!
  }
  return out
}

export function render(all: Record<string, Solved>) {
  return (
    '// Generated by scripts/gen-solved.ts — do not edit. Solved placements per\n' +
    '// character, keyed by a hash of its spec and the solver version.\n' +
    "import type { Solved } from '../character'\n\n" +
    `export const SOLVED: Record<string, Solved> = ${JSON.stringify(all, null, 1)}\n`
  )
}

if (process.argv[1]?.endsWith('gen-solved.ts')) {
  const text = render(solveAll())
  if (process.argv.includes('--check')) {
    const same = readFileSync(OUT, 'utf8') === text
    console.log(same ? 'solved cache is fresh' : 'solved cache is STALE — run pnpm exec tsx scripts/gen-solved.ts')
    process.exit(same ? 0 : 1)
  }
  writeFileSync(OUT, text)
  console.log(`wrote ${OUT} (${Object.keys(JSON.parse(text.slice(text.indexOf('= ') + 2))).length} characters)`)
}
